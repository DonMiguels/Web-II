-- updated_at automatico
CREATE OR REPLACE FUNCTION set_updated_at()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.updated_at = NOW();
    RETURN NEW;
END;
$$;

DO $$
DECLARE
    t TEXT;
    trg_name TEXT;
    tables TEXT[] := ARRAY[
        'group_type', 'person', 'user', 'transaction',
        'item_category', 'item', 'stock',
        'loan', 'loan_item',
        'kit', 'kit_item', 'maintenance', 'compensation'
    ];
BEGIN
    FOREACH t IN ARRAY tables
    LOOP
        trg_name := 'trg_' || t || '_updated_at';
        EXECUTE format('DROP TRIGGER IF EXISTS %I ON %I', trg_name, t);
        EXECUTE format(
            'CREATE TRIGGER %I BEFORE UPDATE ON %I FOR EACH ROW EXECUTE FUNCTION set_updated_at()',
            trg_name,
            t
        );
    END LOOP;
END;
$$;

COMMIT;
