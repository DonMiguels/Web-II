-- equipo | componente
CREATE TABLE IF NOT EXISTS item_category (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    description TEXT,
    is_consumable BOOLEAN NOT NULL DEFAULT FALSE,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_item_category_name UNIQUE (name),
    CONSTRAINT ck_item_category_name_not_blank CHECK (btrim(name) <> '')
);

-- Condicion fisica (Bueno, Danado, Nuevo, Usado)
CREATE TABLE IF NOT EXISTS item_condition (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    description TEXT,
    CONSTRAINT uq_item_condition_name UNIQUE (name),
    CONSTRAINT ck_item_condition_name_not_blank CHECK (btrim(name) <> '')
);

-- Estatus operativo (Disponible, Mantenimiento, Ocupado, Stock, Asignado, Agotado)
CREATE TABLE IF NOT EXISTS item_status (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    description TEXT,
    CONSTRAINT uq_item_status_name UNIQUE (name),
    CONSTRAINT ck_item_status_name_not_blank CHECK (btrim(name) <> '')
);

CREATE TABLE IF NOT EXISTS location (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    description TEXT,
    parent_id BIGINT REFERENCES location(id) ON DELETE SET NULL,
    deleted_at TIMESTAMPTZ,
    CONSTRAINT ck_location_name_not_blank CHECK (btrim(name) <> '')
);

CREATE TABLE IF NOT EXISTS item (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(50) NOT NULL,
    name VARCHAR(120) NOT NULL,
    description TEXT,
    brand VARCHAR(100),
    model VARCHAR(100),
    category_id BIGINT NOT NULL REFERENCES item_category(id) ON DELETE RESTRICT,
    condition_id BIGINT REFERENCES item_condition(id) ON DELETE SET NULL,
    status_id BIGINT REFERENCES item_status(id) ON DELETE SET NULL,
    is_consumable BOOLEAN NOT NULL DEFAULT FALSE,
    cost NUMERIC(12,2) NOT NULL DEFAULT 0,
    acquisition_date DATE,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    deleted_at TIMESTAMPTZ,
    CONSTRAINT ck_item_code_not_blank CHECK (btrim(code) <> ''),
    CONSTRAINT ck_item_name_not_blank CHECK (btrim(name) <> ''),
    CONSTRAINT ck_item_cost_non_negative CHECK (cost >= 0)
);

-- Stock por ubicacion (antes: inventory)
CREATE TABLE IF NOT EXISTS stock (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id BIGINT NOT NULL REFERENCES item(id) ON DELETE RESTRICT,
    location_id BIGINT NOT NULL REFERENCES location(id) ON DELETE RESTRICT,
    quantity INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_stock_item_location UNIQUE (item_id, location_id),
    CONSTRAINT ck_stock_quantity_non_negative CHECK (quantity >= 0)
);

