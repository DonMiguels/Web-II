    CONSTRAINT ck_audit_type_name_not_blank CHECK (btrim(name) <> '')
);

CREATE TABLE IF NOT EXISTS audit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
