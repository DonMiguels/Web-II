CREATE TABLE IF NOT EXISTS payment_method (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    description TEXT,
    CONSTRAINT uq_payment_method_name UNIQUE (name),
    CONSTRAINT ck_payment_method_name_not_blank CHECK (btrim(name) <> '')
);

CREATE TABLE IF NOT EXISTS compensation (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    loan_item_id BIGINT NOT NULL REFERENCES loan_item(id) ON DELETE RESTRICT,
    processed_by_user_id BIGINT NOT NULL REFERENCES "user"(id) ON DELETE RESTRICT,
    borrower_user_id BIGINT NOT NULL REFERENCES "user"(id) ON DELETE RESTRICT,
    payment_method_id BIGINT NOT NULL REFERENCES payment_method(id) ON DELETE RESTRICT,
    amount_paid NUMERIC(12,2) NOT NULL,
    paid_at TIMESTAMPTZ NOT NULL,
    observations TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    deleted_at TIMESTAMPTZ,
    CONSTRAINT ck_compensation_amount_paid_non_negative CHECK (amount_paid >= 0)
);

