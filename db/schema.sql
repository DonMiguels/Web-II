CREATE TABLE IF NOT EXISTS loan_status (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    description TEXT,
    CONSTRAINT uq_loan_status_name UNIQUE (name),
    CONSTRAINT ck_loan_status_name_not_blank CHECK (btrim(name) <> '')
);

CREATE TABLE IF NOT EXISTS loan (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    borrower_user_id BIGINT NOT NULL REFERENCES "user"(id) ON DELETE RESTRICT,
    processed_by_user_id BIGINT REFERENCES "user"(id) ON DELETE RESTRICT,
    status_id BIGINT NOT NULL REFERENCES loan_status(id) ON DELETE RESTRICT,
    booked_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    due_at TIMESTAMPTZ NOT NULL,
    returned_at TIMESTAMPTZ,
    observations TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT ck_loan_due_after_booked CHECK (due_at >= booked_at),
    CONSTRAINT ck_loan_returned_after_booked CHECK (
        returned_at IS NULL OR returned_at >= booked_at
    )
);

CREATE TABLE IF NOT EXISTS loan_item (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    loan_id BIGINT NOT NULL REFERENCES loan(id) ON DELETE RESTRICT,
    stock_id BIGINT NOT NULL REFERENCES stock(id) ON DELETE RESTRICT,
    quantity INTEGER NOT NULL DEFAULT 1,
    returned_quantity INTEGER NOT NULL DEFAULT 0,
    fine NUMERIC(12,2) NOT NULL DEFAULT 0,
    return_condition_id BIGINT REFERENCES item_condition(id) ON DELETE SET NULL,
    observations TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT ck_loan_item_quantity_positive CHECK (quantity > 0),
    CONSTRAINT ck_loan_item_returned_qty CHECK (
        returned_quantity >= 0 AND returned_quantity <= quantity
    ),
    CONSTRAINT ck_loan_item_fine_non_negative CHECK (fine >= 0)
);

