CREATE TABLE IF NOT EXISTS notification (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(150) NOT NULL,
    message TEXT NOT NULL,
    sent_at TIMESTAMPTZ,
    is_read BOOLEAN NOT NULL DEFAULT FALSE,
    user_id BIGINT NOT NULL REFERENCES "user"(id) ON DELETE RESTRICT,
    type_id BIGINT NOT NULL REFERENCES notification_type(id) ON DELETE RESTRICT,
    CONSTRAINT ck_notification_title_not_blank CHECK (btrim(title) <> ''),
    CONSTRAINT ck_notification_message_not_blank CHECK (btrim(message) <> '')
